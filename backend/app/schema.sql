-- British Auction RFQ schema (PostgreSQL 13+). Idempotent: applied automatically on API startup.

DO $$ BEGIN
  CREATE TYPE trigger_type AS ENUM ('BID_RECEIVED', 'ANY_RANK_CHANGE', 'L1_CHANGE');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE auction_status AS ENUM ('UPCOMING', 'ACTIVE', 'CLOSED', 'FORCE_CLOSED');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE activity_event AS ENUM
    ('RFQ_CREATED', 'BID_SUBMITTED', 'TIME_EXTENDED', 'AUCTION_CLOSED', 'AUCTION_FORCE_CLOSED');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- RFQ + its British Auction configuration (1:1, so same table)
CREATE TABLE IF NOT EXISTS rfqs (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_id        VARCHAR(40)    NOT NULL UNIQUE,
  name                VARCHAR(200)   NOT NULL,
  pickup_date         DATE           NOT NULL,
  bid_start_at        TIMESTAMPTZ    NOT NULL,
  bid_close_at        TIMESTAMPTZ    NOT NULL,          -- original close, never changes
  current_close_at    TIMESTAMPTZ    NOT NULL,          -- live close, moved by extensions
  forced_close_at     TIMESTAMPTZ    NOT NULL,          -- hard stop
  trigger_window_min  INTEGER        NOT NULL CHECK (trigger_window_min BETWEEN 1 AND 1440),  -- X
  extension_min       INTEGER        NOT NULL CHECK (extension_min BETWEEN 1 AND 1440),       -- Y
  trigger_type        trigger_type   NOT NULL,
  status              auction_status NOT NULL DEFAULT 'UPCOMING',
  extension_count     INTEGER        NOT NULL DEFAULT 0,
  created_at          TIMESTAMPTZ    NOT NULL DEFAULT now(),
  CONSTRAINT chk_close_after_start   CHECK (bid_close_at > bid_start_at),
  CONSTRAINT chk_forced_after_close  CHECK (forced_close_at > bid_close_at),
  CONSTRAINT chk_current_close_range CHECK (current_close_at BETWEEN bid_close_at AND forced_close_at)
);

-- Sweeper only looks at auctions that can still change state
CREATE INDEX IF NOT EXISTS idx_rfqs_open ON rfqs (current_close_at) WHERE status IN ('UPCOMING', 'ACTIVE');

CREATE TABLE IF NOT EXISTS suppliers (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL,                    -- carrier name
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_suppliers_name_ci ON suppliers (lower(name));

CREATE TABLE IF NOT EXISTS bids (
  id                   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  rfq_id               BIGINT        NOT NULL REFERENCES rfqs (id) ON DELETE CASCADE,
  supplier_id          BIGINT        NOT NULL REFERENCES suppliers (id),
  freight_charges      NUMERIC(12,2) NOT NULL CHECK (freight_charges >= 0),
  origin_charges       NUMERIC(12,2) NOT NULL CHECK (origin_charges >= 0),
  destination_charges  NUMERIC(12,2) NOT NULL CHECK (destination_charges >= 0),
  total_amount         NUMERIC(14,2) GENERATED ALWAYS AS (freight_charges + origin_charges + destination_charges) STORED,
  transit_time_days    INTEGER       NOT NULL CHECK (transit_time_days BETWEEN 1 AND 365),
  quote_valid_until    DATE          NOT NULL,
  created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
  CONSTRAINT chk_total_positive CHECK (freight_charges + origin_charges + destination_charges > 0)
);

CREATE INDEX IF NOT EXISTS idx_bids_rfq_price    ON bids (rfq_id, total_amount, created_at, id);
CREATE INDEX IF NOT EXISTS idx_bids_rfq_supplier ON bids (rfq_id, supplier_id);

CREATE TABLE IF NOT EXISTS activity_logs (
  id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  rfq_id        BIGINT         NOT NULL REFERENCES rfqs (id) ON DELETE CASCADE,
  event_type    activity_event NOT NULL,
  bid_id        BIGINT         REFERENCES bids (id) ON DELETE SET NULL,
  supplier_id   BIGINT         REFERENCES suppliers (id),
  old_close_at  TIMESTAMPTZ,                             -- TIME_EXTENDED only
  new_close_at  TIMESTAMPTZ,                             -- TIME_EXTENDED only
  reason        TEXT,                                    -- why the auction was extended
  message       TEXT           NOT NULL,
  created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
  CONSTRAINT chk_extension_fields CHECK (
    event_type <> 'TIME_EXTENDED'
    OR (old_close_at IS NOT NULL AND new_close_at > old_close_at AND reason IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_activity_rfq ON activity_logs (rfq_id, created_at, id);
